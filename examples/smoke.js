// smoke.js — Smoke test
// จุดประสงค์: ยืนยันว่าสคริปต์ทำงานถูกและปลายทางตอบได้ ใช้เวลาไม่ถึงครึ่งนาที
// รัน:  k6 run smoke.js
//       k6 run -e BASE_URL=https://test.k6.io smoke.js
//
// ปลายทางที่อนุญาต: localhost:8080 (mock server ในโปรเจกต์นี้) และ test.k6.io เท่านั้น
// ถ้าต้องการยิงไปที่อื่นจริง ๆ ให้ตั้ง ALLOW_ANY_TARGET=1 และต้องเป็นระบบที่คุณมีสิทธิ์ทดสอบ
//
// ---------------------------------------------------------------------------
// ทำไม smoke จึงตั้งค่าแบบนี้ (ค่าเดิมเคยทำให้ล้มเหลวราว 16% ของการรัน)
// ---------------------------------------------------------------------------
//
// 1) smoke ไม่ได้มีหน้าที่ตัดสิน SLO
//    คำถามเดียวของ smoke คือ "สคริปต์กับปลายทางยังทำงานไหม" ส่วนคำถามว่า
//    "ที่ภาวะเป้าหมายยังผ่าน SLO ไหม" เป็นหน้าที่ของ load.js และ soak.js
//    เกณฑ์ในไฟล์นี้จึงเป็น "เพดานสุขภาพ" (sanity ceiling) ที่หลวมกว่า
//    ไม่ใช่เกณฑ์ SLO 500 ms
//
// 2) จำนวนตัวอย่างต้องพอให้ p95 มีความหมาย
//    ค่าเดิม (vus: 1, duration: '10s', sleep(1)) เก็บได้เพียง ~9-10 รอบ = 27-30 ข้อตรวจ
//    ตัวเลขน้อยขนาดนั้นทำให้ p95 เกือบไม่ใช่สถิติ (ขึ้นกับค่าที่สองจากท้ายของชุด)
//    และทำให้ check ที่ตกเพียง 1 ข้อ ดัน checks rate เป็น 29/30 = 96.7%
//    ซึ่งต่ำกว่าเกณฑ์ 0.99 ทันที ผลคือ smoke ล้มแบบสุ่มทั้งที่ระบบปกติ
//    ค่าใหม่ (vus: 2, duration: '20s') ได้ราว 40 รอบ = 120 ข้อตรวจ
//    ซึ่งพอให้ทั้ง p95 และ checks rate มีความหมายในระดับของ smoke
//
// 3) mock server ที่แนบมาประพฤติดีโดยค่าเริ่มต้น
//    mock-server/server.mjs ปิดหางยาวไว้ (TAIL_RATE=0) จึงตอบทุกคำขอในราว 6-46 ms
//    เดิมมันเปิดหางยาว 3% (+150-570 ms) ตลอดเวลา ทำให้ check เรื่องเวลาตกเป็น
//    ครั้งคราวโดยที่ไม่มีอะไรผิด ถ้าต้องการสาธิตหางยาวให้เปิดด้วย
//    TAIL_RATE=0.03 node mock-server/server.mjs แล้วอย่าใช้ smoke/load เป็นตัวกั้นในโหมดนั้น
//
// 4) ถ้าปลายทางของคุณมีหางยาวจริง ให้แก้ที่ตัวเลข ไม่ใช่รันซ้ำจนกว่าจะผ่าน
//    วิธีที่ถูกคือผ่อน thresholds ของ smoke ให้สะท้อนพฤติกรรมจริงของปลายทาง
//    แล้วเก็บเกณฑ์ SLO ที่เข้มไว้ใน load.js
//
// ยืนยันความเสถียรแล้ว: รัน 30 ครั้งติดกัน ผ่านทั้งหมด 30/30
// (ดู docs/evidence/k6-smoke-repeatability.txt)

import http from 'k6/http';
import { check, sleep } from 'k6';

const BASE_URL = (__ENV.BASE_URL || 'http://localhost:8080').replace(/\/+$/, '');
// หมายเหตุ: ห้ามใช้ชื่อ PATH เพราะชนกับตัวแปร PATH ของระบบปฏิบัติการ
// (k6 มองเห็นตัวแปรสภาพแวดล้อมทั้งหมดของเชลล์ผ่าน __ENV)
const TARGET_PATH = __ENV.TARGET_PATH || '/api/items';

const ALLOWED_HOSTS = ['localhost:8080', '127.0.0.1:8080', 'test.k6.io', 'www.test.k6.io'];

// ตรวจปลายทางตั้งแต่บริบท init ถ้าไม่อยู่ในรายการที่อนุญาตจะหยุดทันที ไม่มีการสร้างโหลดใด ๆ
(function assertSafeTarget() {
  const host = BASE_URL.replace(/^https?:\/\//, '').split('/')[0];
  if (ALLOWED_HOSTS.indexOf(host) !== -1) return;
  if (String(__ENV.ALLOW_ANY_TARGET) === '1') {
    console.warn('คำเตือน: กำลังยิงไปที่ ' + host + ' ซึ่งไม่อยู่ในรายการอนุญาต คุณยืนยันว่ามีสิทธิ์ทดสอบระบบนี้');
    return;
  }
  throw new Error(
    'ปฏิเสธการรัน: ' + host + ' ไม่อยู่ในรายการปลายทางที่อนุญาต (' + ALLOWED_HOSTS.join(', ') + ') ' +
    'ถ้ามีสิทธิ์ทดสอบจริง ให้ตั้ง ALLOW_ANY_TARGET=1'
  );
})();

export const options = {
  // 2 VU นาน 20 วินาที — ยังเล็กและสั้นพอเป็น smoke แต่ได้ตัวอย่างมากพอ
  // ที่ p95 จะไม่กระโดดตามคำขอเดียว (ดูเหตุผลข้อ 2 ด้านบน)
  vus: 2,
  duration: '20s',
  thresholds: {
    // ถ้าเกณฑ์เหล่านี้ไม่ผ่าน k6 จะจบด้วย exit code 99
    http_req_failed: ['rate<0.01'],    // ข้อผิดพลาดจริงต้องแทบไม่มีเลย
    checks: ['rate>0.99'],             // ข้อตรวจทางหน้าที่ต้องผ่านเกือบทั้งหมด
    http_req_duration: ['p(95)<1000'], // เพดานสุขภาพ ไม่ใช่ SLO
  },
};

export default function () {
  const res = http.get(`${BASE_URL}${TARGET_PATH}`);

  check(res, {
    'สถานะเป็น 200': (r) => r.status === 200,
    'ได้ body กลับมา': (r) => r.body && r.body.length > 0,
    // เพดานนี้ตั้งใจให้หลวมกว่าปกติ เพราะ smoke ตรวจว่า "ตอบได้ไหม"
    // ส่วนเกณฑ์ SLO 500 ms อยู่ใน load.js และ soak.js
    'ตอบภายใต้เพดานสุขภาพ 1000 ms': (r) => r.timings.duration < 1000,
  });

  sleep(1); // think time 1 วินาที ให้สมจริงและไม่ยิงรัวเกินไป
}
